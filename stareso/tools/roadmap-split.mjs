// One-off migration: splits a single docs/ROADMAP.md into docs/ROADMAP.md (header + overview table + list)
// and one file per milestone in docs/roadmap/<ID>.md. Sections whose heading is not "## <ID>. Title"
// go to docs/roadmap/notes.md. Refuses to run when docs/roadmap/ already exists.
//   node ~/.claude/stareso/tools/roadmap-split.mjs
import fs from "node:fs";
import path from "node:path";
import { findRoot, readText, writeText, writeOverview, OVERVIEW_START, OVERVIEW_END } from "./lib/roadmap.mjs";

const root = findRoot();
const dir = path.join(root, "docs", "roadmap");
if (fs.existsSync(dir)) { console.error("docs/roadmap/ already exists: nothing to split."); process.exit(1); }
const file = path.join(root, "docs", "ROADMAP.md");
const { lines, eol } = readText(file);

const firstSection = lines.findIndex((l) => /^## /.test(l));
if (firstSection < 0) { console.error("No '## ' sections in docs/ROADMAP.md."); process.exit(1); }
const header = lines.slice(0, firstSection);

const sections = [];
let cur = null;
for (const l of lines.slice(firstSection)) {
  if (/^## /.test(l)) { cur = { heading: l.replace(/^## /, ""), body: [] }; sections.push(cur); }
  else cur.body.push(l);
}

fs.mkdirSync(dir);
const notes = [];
const written = [];
for (const s of sections) {
  const m = /^([A-Za-z]+\d*)\. (.+)$/.exec(s.heading);
  const body = trimBlank(s.body);
  if (!m) { notes.push(`## ${s.heading}`, ...body, ""); continue; }
  const out = path.join(dir, `${m[1]}.md`);
  writeText(out, [`# ${m[1]}. ${m[2]}`, "", ...body, ""], eol);
  written.push(path.basename(out));
}
if (notes.length) { writeText(path.join(dir, "notes.md"), ["# Notes (sections of the old roadmap without a milestone id)", "", ...notes], eol); written.push("notes.md"); }

const newRoadmap = [
  ...trimBlank(header),
  "",
  "## Overview",
  "",
  "One file per milestone in `docs/roadmap/` (`M1.md`, `H.md`…). This table is regenerated by the tools (`slice-done`, `roadmap-overview`); edit the milestone files, not the table.",
  "",
  OVERVIEW_START,
  OVERVIEW_END,
  "",
];
writeText(file, newRoadmap, eol);
writeOverview(root);
console.log(`Split into ${written.length} files: ${written.join(", ")}`);
console.log("Check docs/README.md (add docs/roadmap/) and the briefs' guide paths, then commit.");

function trimBlank(arr) {
  let a = 0, b = arr.length;
  while (a < b && arr[a] === "") a++;
  while (b > a && arr[b - 1] === "") b--;
  return arr.slice(a, b);
}
